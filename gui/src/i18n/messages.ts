export type MessageKey = keyof typeof MESSAGES.ko;

/** Replaces each {name} with String(params.name); a placeholder with no parameter is left as it is. */
export function t(lang: Lang, key: MessageKey, params?: Record<string, string | number>): string {
  const text: string = MESSAGES[lang][key];
  if (!params) return text;
  return text.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/gu, (whole, name: string) => (Object.hasOwn(params, name) ? String(params[name]) : whole));
}

/** 'ko' or a 'ko-…' locale gives 'ko'; anything else gives 'en'. */
export function langFromLocale(locale: string | undefined): Lang {
  if (!locale) return 'en';
  const language = locale.toLowerCase().split(/[-_]/u)[0];
  return language === 'ko' ? 'ko' : 'en';
}
